#!/usr/bin/env bash
# Generate the body of CodesWhat/homebrew-tap's Casks/mouthtype.rb.
#
# Prints the cask to stdout by default; pass --write <path> to write it to a
# file instead (the tap's update-mouthtype-cask workflow does this). Version
# comes from packaging/Version.plist unless --version overrides it. sha256 is
# computed from a real DMG: pass --dmg <path> to hash a local build, or the
# script downloads the published release DMG for the resolved version and
# hashes that, so the digest provably matches what users download.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

usage() {
	echo "Usage: $0 [--version X.Y.Z] [--dmg /path/to.dmg] [--write /path/to/mouthtype.rb]" >&2
	exit "${1:-64}"
}

VERSION=""
DMG_PATH=""
WRITE_PATH=""

while [ $# -gt 0 ]; do
	case "$1" in
	--version)
		VERSION="${2:-}"
		[ -n "$VERSION" ] || usage
		shift 2
		;;
	--dmg)
		DMG_PATH="${2:-}"
		[ -n "$DMG_PATH" ] || usage
		shift 2
		;;
	--write)
		WRITE_PATH="${2:-}"
		[ -n "$WRITE_PATH" ] || usage
		shift 2
		;;
	-h | --help)
		usage 0
		;;
	*)
		usage
		;;
	esac
done

if [ -z "$VERSION" ]; then
	VERSION="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' "$REPO_ROOT/packaging/Version.plist")"
fi

# The version lands unescaped inside the cask body and the download URL, so a
# malformed override (a stray quote, a leading "v", a prerelease suffix) would
# emit invalid Ruby or a URL that 404s while the script still exits 0. Bare
# X.Y.Z only.
if ! printf '%s' "$VERSION" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+$'; then
	echo "error: version must be bare X.Y.Z (got: $VERSION)" >&2
	exit 65
fi

TMP_DIR=""
WRITE_TMP=""
cleanup() {
	[ -z "$TMP_DIR" ] || rm -rf "$TMP_DIR"
	[ -z "$WRITE_TMP" ] || rm -f "$WRITE_TMP"
}
trap cleanup EXIT

if [ -z "$DMG_PATH" ]; then
	DMG_NAME="Mouthtype-$VERSION-macos-arm64.dmg"
	DMG_URL="https://github.com/CodesWhat/mouthtype/releases/download/v$VERSION/$DMG_NAME"
	TMP_DIR="$(mktemp -d)"
	DMG_PATH="$TMP_DIR/$DMG_NAME"
	echo "Downloading $DMG_URL ..." >&2
	curl -fsSL -o "$DMG_PATH" "$DMG_URL"
fi

if [ ! -f "$DMG_PATH" ] || [ ! -r "$DMG_PATH" ]; then
	echo "error: DMG not found or not readable at $DMG_PATH" >&2
	exit 66
fi

# --write and --dmg pointing at the same file would clobber the input DMG.
# cd -P compares physical paths, so a symlinked directory can't sneak the
# same file in under two names.
if [ -n "$WRITE_PATH" ] && [ -e "$WRITE_PATH" ] &&
	[ "$(cd -P "$(dirname "$WRITE_PATH")" && pwd)/$(basename "$WRITE_PATH")" = \
		"$(cd -P "$(dirname "$DMG_PATH")" && pwd)/$(basename "$DMG_PATH")" ]; then
	echo "error: --write and --dmg resolve to the same file" >&2
	exit 67
fi

SHA256="$(shasum -a 256 "$DMG_PATH" | awk '{print $1}')"

emit_cask() {
	cat <<EOF
# This file was generated by scripts/generate-homebrew-cask.sh in
# CodesWhat/mouthtype. DO NOT EDIT.
cask "mouthtype" do
  version "$VERSION"
  sha256 "$SHA256"

  url "https://github.com/CodesWhat/mouthtype/releases/download/v#{version}/Mouthtype-#{version}-macos-arm64.dmg"
  name "Mouthtype"
  desc "Local voice dictation with on-device cleanup"
  homepage "https://mouthtype.app/"

  livecheck do
    url :url
    strategy :github_latest
  end

  auto_updates true
  depends_on arch: :arm64
  # Matches LSMinimumSystemVersion (26.0) in the app's Info.plist.
  depends_on macos: :tahoe

  app "Mouthtype.app"

  uninstall quit: "com.codeswhat.mouthtype"

  # Dictation history and drafts live under Application Support. Only
  # \`brew uninstall --zap\` removes them; a plain uninstall leaves them.
  zap trash: [
    "~/Library/Application Support/Mouthtype",
    "~/Library/Caches/com.codeswhat.mouthtype",
    "~/Library/Caches/Mouthtype",
    "~/Library/HTTPStorages/com.codeswhat.mouthtype",
    "~/Library/Preferences/com.codeswhat.mouthtype.plist",
    "~/Library/Saved Application State/com.codeswhat.mouthtype.savedState",
  ]

  caveats <<~EOS
    Mouthtype is Apple silicon only and needs macOS 26 or later.
    Grant Microphone and Accessibility access when it asks. The speech model downloads on first launch.
    The app updates itself with Sparkle, so \`brew upgrade\` is optional.
  EOS
end
EOF
}

if [ -n "$WRITE_PATH" ]; then
	# Write via a temp file in the destination dir so a mid-write failure
	# can't leave a truncated cask behind.
	WRITE_TMP="$(mktemp "$(dirname "$WRITE_PATH")/.mouthtype.rb.XXXXXX")"
	emit_cask >"$WRITE_TMP"
	mv "$WRITE_TMP" "$WRITE_PATH"
	echo "Wrote cask to $WRITE_PATH" >&2
else
	emit_cask
fi
