"""Two bitmap fonts: 5x7 (the readout face, caps and digits) and 3x5 (tiny labels, timers).
Glyphs are rows joined by '/', '#' is ink."""


def _mk(spec, w, h):
    out = {}
    for ch, rows in spec.items():
        r = rows.split("/")
        assert len(r) == h and all(len(x) == w for x in r), (ch, rows)
        out[ch] = r
    out[" "] = ["." * w] * h
    return out


