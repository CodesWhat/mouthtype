// Generates src/lib/analytics-routes.generated.ts: the canonical page paths the analytics
// sanitizer accepts, taken from docs-manifest.mjs (the single source of truth for the docs
// tree). Run with --check in CI and before build to catch a stale list.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { destToUrl, pages } from "./docs-manifest.mjs";

const SCRIPT_FILE = fileURLToPath(import.meta.url);
const TARGET = path.join(
  path.dirname(SCRIPT_FILE),
  "..",
  "src",
  "lib",
  "analytics-routes.generated.ts",
);

/** Page URLs without a trailing slash, sorted, "/" first. */
export function collectAnalyticsRoutes(manifestPages = pages) {
  const routes = new Set(manifestPages.map((page) => destToUrl(page.dest)));
  return [...routes].sort();
}

export function renderAnalyticsRoutes(routes) {
  const values = routes.map((route) => `  ${JSON.stringify(route)},`).join("\n");
  return `// Generated by scripts/analytics-routes.mjs. Do not edit by hand.\nconst routes = [\n${values}\n] as const;\n\nexport const ANALYTICS_ROUTES: ReadonlySet<string> = new Set(routes);\n`;
}

export function routesAreCurrent(target, expected) {
  try {
    return fs.readFileSync(target, "utf8") === expected;
  } catch {
    return false;
  }
}

function main() {
  const expected = renderAnalyticsRoutes(collectAnalyticsRoutes());
  if (process.argv.includes("--check")) {
    if (!routesAreCurrent(TARGET, expected)) {
      console.error("Analytics routes are stale. Run: npm run sync:analytics-routes");
      process.exitCode = 1;
    }
    return;
  }
  fs.writeFileSync(TARGET, expected);
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  main();
}
