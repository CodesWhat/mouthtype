#!/usr/bin/env python3
"""Regenerate IconData.js from icons/*.svg, or check that it is current (--check).

Icon.qml draws each glyph from an inline SVG data URL so the colour is baked into the path fill. That works on both the
GPU and software Qt Quick backends, where a shader tint would not. The .svg files stay the source of truth.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PATH_RE = re.compile(r'<path d="([^"]+)"')


def collect():
    icons = {}
    for svg in sorted((HERE / "icons").glob("*.svg")):
        paths = PATH_RE.findall(svg.read_text())
        if not paths:
            raise SystemExit(f"{svg.name}: no <path d=...> found")
        icons[svg.stem] = " ".join(paths)
    return icons


def render(icons):
    lines = [
        ".pragma library",
        "",
        "// Generated by gen_icons.py from icons/*.svg (Pixelarticons v2.4.2, MIT). Do not edit by hand.",
        "// Each value is the concatenated path data of a 24x24 glyph.",
        "",
        "var paths = {",
    ]
    items = sorted(icons.items())
    for index, (name, data) in enumerate(items):
        comma = "," if index < len(items) - 1 else ""
        lines.append(f'  "{name}": "{data}"{comma}')
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main():
    out = HERE / "IconData.js"
    text = render(collect())
    if "--check" in sys.argv:
        if not out.exists() or out.read_text() != text:
            raise SystemExit("IconData.js is out of date; run gen_icons.py")
        return
    out.write_text(text)


if __name__ == "__main__":
    main()
