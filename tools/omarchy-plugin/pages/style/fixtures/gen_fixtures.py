"""Writes StyleFixtures.js: `style-state` replies for the Style page scenes, made by the real styles.describe so the shape
cannot drift from the backend. test_style_page.py fails when the file is out of date. Run: python3 gen_fixtures.py"""
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
DESKTOP = HERE.parents[3] / "linux-desktop"
sys.path.insert(0, str(DESKTOP))

import styles  # noqa: E402

POPULATED = {
    "version": 1,
    "tone": "formal",
    "contexts": {
        "personal": {"tone": "casual", "cleanup": None,
                     "added": [{"app": "org.example.Chat", "name": "Chat"}], "removed": ["discord"]},
        "work": {"tone": "formal", "cleanup": "thorough", "added": [], "removed": []},
        "email": {"tone": None, "cleanup": None, "added": [{"app": "mailspring", "name": "Mailspring"}], "removed": []},
        "other": {"tone": None, "cleanup": "basic", "added": [], "removed": []},
    },
    "rules": [
        {"app": "Slack", "name": "Slack", "tone": "very_casual", "cleanup": None},
        {"app": "com.slack.Slack", "name": "Slack", "tone": "very_casual", "cleanup": None},
        {"app": "foot", "name": "foot", "tone": None, "cleanup": "off"},
    ],
}


def fixtures():
    return {
        "fresh": styles.describe(styles.validate(None)),
        "populated": styles.describe(styles.validate(POPULATED)),
    }


def render():
    body = "".join("var %s = %s\n\n" % (name, json.dumps(value, indent=2, sort_keys=True))
                   for name, value in fixtures().items())
    return ".pragma library\n\n// Generated by gen_fixtures.py from tools/linux-desktop/styles.py. Do not edit.\n\n" + body


if __name__ == "__main__":
    (HERE / "StyleFixtures.js").write_text(render(), encoding="utf-8")
