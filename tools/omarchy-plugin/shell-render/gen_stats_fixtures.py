#!/usr/bin/env python3
"""Writes StatsFixtures.js: real `stats` JSON for the Stats page render tests, built by tools/linux-desktop/stats.py from
synthetic takes at a fixed clock (2026-10-20 15:20 UTC, tz UTC), so the shapes are the ones control.py prints.

    python3 tools/omarchy-plugin/shell-render/gen_stats_fixtures.py          # rewrite StatsFixtures.js
    python3 tools/omarchy-plugin/shell-render/gen_stats_fixtures.py --check  # exit 1 if the file is stale
"""
import importlib.util
import json
import random
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUTPUT = HERE / 'StatsFixtures.js'
STATS = HERE.parents[1] / 'linux-desktop' / 'stats.py'
NOW = datetime(2026, 10, 20, 15, 20, tzinfo=timezone.utc)
NOW_SECONDS = 15 * 3600 + 20 * 60
DAY = 86400


def load():
    spec = importlib.util.spec_from_file_location('mouthtype_stats_fixture_engine', STATS)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def at(days_ago, hour, minute=0, second=0):
    base = NOW.replace(hour=hour, minute=minute, second=second, microsecond=0)
    return base.timestamp() - days_ago * DAY


def scenes(engine):
    now = NOW.timestamp()
    counter = [0]

    def take(started, words, seconds=None, audio_only=False):
        counter[0] += 1
        return engine.Take('%032x' % counter[0], started, words, None if seconds is None else int(seconds * 1000), audio_only)

    out = {}
    out['empty'] = engine.build([], now=now, tz=timezone.utc)

    out['one_take'] = engine.build([take(at(0, 14, 5), 38, 11)], now=now, tz=timezone.utc)

    # A few days spread over three weeks with gaps. Today: two close takes that merge, an audio-only take, and a long one.
    sparse = []
    for days_ago, hour, words, seconds in [(19, 9, 120, 55), (18, 9, 80, 40), (12, 16, 310, 140), (5, 11, 45, 20),
                                          (4, 11, 210, 90), (1, 20, 66, 30)]:
        sparse.append(take(at(days_ago, hour, 12), words, seconds))
    sparse += [take(at(0, 9, 30), 52, 21), take(at(0, 9, 31), 18, 8), take(at(0, 11, 2), 0, None, True),
               take(at(0, 13, 40), 240, 95), take(at(0, 15, 10), 31, 12)]
    out['sparse'] = engine.build(sparse, now=now, tz=timezone.utc)

    # A full month: a take or three every day, today with forty needles including a merged cluster and audio-only takes.
    rng = random.Random(20261020)
    dense = []
    for days_ago in range(1, 41):
        if days_ago in (9, 10):
            continue
        for _ in range(rng.randint(1, 4)):
            words = rng.randint(8, 420)
            dense.append(take(at(days_ago, rng.choice([8, 9, 10, 11, 14, 14, 15, 15, 16, 21]), rng.randint(0, 59)),
                              words, words * 60 / rng.uniform(95, 190)))
    seconds_of_day = 7 * 3600 + 40 * 60
    while seconds_of_day < 15 * 3600 + 10 * 60:
        words = rng.choice([6, 12, 25, 40, 70, 110, 180, 360])
        dense.append(take(at(0, 0) + seconds_of_day, words, words * 60 / rng.uniform(100, 180)))
        seconds_of_day += rng.choice([4 * 60, 9 * 60, 17 * 60, 31 * 60])
    dense += [take(at(0, 12, 0, 0), 20, 9), take(at(0, 12, 0, 20), 33, 14), take(at(0, 12, 0, 40), 0, None, True),
              take(at(0, 12, 1, 5), 410, 150), take(at(0, 10, 15), 0, None, True)]
    out['dense'] = engine.build(dense, now=now, tz=timezone.utc)

    # Only audio today and nothing with a transcript anywhere: the tape shows alone.
    out['audio_only'] = engine.build([take(at(0, 10, 5), 0, None, True), take(at(0, 10, 40), 0, None, True)],
                                     now=now, tz=timezone.utc)
    return out


def render():
    engine = load()
    body = json.dumps(scenes(engine), indent=1, sort_keys=True)
    return ('.pragma library\n'
            '// Generated by gen_stats_fixtures.py from tools/linux-desktop/stats.py. Do not edit; rerun the script.\n'
            '// The clock is 2026-10-20 15:20 UTC; nowSeconds is that time as seconds into the day.\n'
            'var nowSeconds = %d\n'
            'var scenes = %s\n' % (NOW_SECONDS, body))


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        sys.exit(0 if OUTPUT.read_text() == text else 1)
    OUTPUT.write_text(text)
